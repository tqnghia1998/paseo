import { execFileSync } from "node:child_process";
import { copyFile, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const repository = "https://github.com/ABorakati/beautiful-chat.git";
const revision = "42b61d8301b5400a67821bbbfcf99fa8b681dc37";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const destination = path.join(root, "plugins/beautiful-chat");
const source = await mkdtemp(path.join(os.tmpdir(), "paseo-beautiful-chat-"));

try {
  execFileSync("git", ["init", "-q", source]);
  execFileSync("git", ["-C", source, "fetch", "--depth=1", repository, revision], {
    stdio: "inherit",
  });
  execFileSync("git", ["-C", source, "checkout", "--detach", "-q", "FETCH_HEAD"]);
  execFileSync("git", [
    "-C",
    source,
    "apply",
    path.join(root, "scripts/beautiful-chat-vibing.patch"),
  ]);
  execFileSync(
    process.platform === "win32" ? "npm.cmd" : "npm",
    ["ci", "--omit=dev", "--ignore-scripts", "--no-fund", "--no-audit"],
    { cwd: source, stdio: "inherit" },
  );

  for (const target of ["client", "server"]) {
    const directory = path.join(destination, target);
    await mkdir(directory, { recursive: true });
    await build({
      absWorkingDir: source,
      entryPoints: [target === "client" ? "index.client.tsx" : "index.server.ts"],
      outfile: path.join(directory, "beautiful-chat.gen.ts"),
      bundle: true,
      format: "esm",
      platform: target === "client" ? "browser" : "node",
      target: "es2022",
      jsx: "automatic",
      external: [
        "@getpaseo/plugin",
        "@getpaseo/plugin/*",
        "zod",
        "react",
        "react/*",
        "react-native",
        "@tanstack/react-query",
      ],
      banner: {
        js: `// @ts-nocheck\n// Generated by scripts/vendor-beautiful-chat.mjs from ABorakati/beautiful-chat@${revision}.`,
      },
      legalComments: "eof",
    });
  }

  await copyFile(path.join(source, "LICENSE"), path.join(destination, "LICENSE"));
  const lock = JSON.parse(await readFile(path.join(source, "package-lock.json"), "utf8"));
  const notices = [];
  for (const [relative, entry] of Object.entries(lock.packages)) {
    if (!relative || entry.dev) continue;
    const directory = path.join(source, relative);
    const manifest = JSON.parse(await readFile(path.join(directory, "package.json"), "utf8"));
    const licenseName = (await readdir(directory)).find((name) => /^license(?:[.-]|$)/i.test(name));
    if (!licenseName) throw new Error(`Missing license for ${manifest.name}`);
    const license = await readFile(path.join(directory, licenseName), "utf8");
    notices.push(`${manifest.name}@${manifest.version}\n${license}`);
  }
  await writeFile(path.join(destination, "THIRD_PARTY_LICENSES.txt"), notices.join("\n\n"));
} finally {
  await rm(source, { recursive: true, force: true });
}
